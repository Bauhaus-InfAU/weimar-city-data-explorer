#!/usr/bin/env python3
"""
export_space_syntax_gpkg.py — TASK_34 part 4: GeoPackages for manual editing in QGIS.

Writes, in EPSG:25832 (geopandas / pyogrio):
  output/qgis/weimar_ss_car.gpkg          layers: network (weimar_ss_car_strong.geojson, v2/TASK_32, untouched)
                                                   removed (weimar_ss_car_strong_removed.geojson)
  output/qgis/weimar_ss_pedestrian.gpkg   layers: network (weimar_ss_pedestrian_<preset>.geojson)
                                                   removed (weimar_ss_pedestrian_<preset>_removed.geojson)
  output/qgis/weimar_ss_union.gpkg        layer:  union (car + pedestrian together, `network` field; for
                                                          visual reference only — do not edit this one, it is
                                                          not read back by anything)

Run:  python tools/export_space_syntax_gpkg.py [preset]      (default preset for pedestrian: medium)
"""
import json, sys
from pathlib import Path

import geopandas as gpd
from shapely.geometry import shape

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "web" / "layers" / "data"
OUT = ROOT / "output" / "qgis"


def _gdf(path):
    fc = json.load(open(path, encoding="utf-8"))
    if not fc["features"]:
        return gpd.GeoDataFrame(columns=["geometry"], geometry="geometry", crs="EPSG:4326").to_crs(25832)
    props = [f["properties"] for f in fc["features"]]
    geoms = [shape(f["geometry"]) for f in fc["features"]]
    return gpd.GeoDataFrame(props, geometry=geoms, crs="EPSG:4326").to_crs(25832)


def write(path, layers):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        path.unlink()
    for name, gdf in layers.items():
        gdf.to_file(path, layer=name, driver="GPKG")
    print(path, "->", list(layers))


def main(preset="medium"):
    write(OUT / "weimar_ss_car.gpkg", {
        "network": _gdf(DATA / "weimar_ss_car_strong.geojson"),
        "removed": _gdf(DATA / "weimar_ss_car_strong_removed.geojson"),
    })
    write(OUT / "weimar_ss_pedestrian.gpkg", {
        "network": _gdf(DATA / f"weimar_ss_pedestrian_{preset}.geojson"),
        "removed": _gdf(DATA / f"weimar_ss_pedestrian_{preset}_removed.geojson"),
    })
    union_path = DATA / "weimar_ss_union_check.geojson"
    if union_path.exists():
        write(OUT / "weimar_ss_union.gpkg", {"union": _gdf(union_path)})
    readme = OUT / "README.txt"
    readme.write_text(
        "TASK_34 — Space Syntax networks for manual editing in QGIS (EPSG:25832)\n"
        "========================================================================\n\n"
        "weimar_ss_car.gpkg          layer 'network' = the car reference (v2/TASK_32), layer 'removed' = what\n"
        "                            the automatic rules took out (for reference — car is not meant to be\n"
        "                            re-derived, but you can still hand-edit it if needed).\n"
        f"weimar_ss_pedestrian.gpkg  layer 'network' = pedestrian preset '{preset}', layer 'removed' = what the\n"
        "                            rules took out (turn it on to see what you might want back).\n"
        "weimar_ss_union.gpkg        layer 'union' = car + pedestrian together (field 'network' tells them\n"
        "                            apart) — for LOOKING at how they line up. Do not edit this file; it is\n"
        "                            regenerated by tools/check_ss_car_reference.py and never read back.\n\n"
        "DO NOT CHANGE the `ssId` field on features you keep — tools/import_space_syntax_edited.py matches your\n"
        "edited file back to the manifest by ssId. New drawn segments can be left without an ssId (or any\n"
        "value) — the import script assigns fresh ones.\n\n"
        "When you are done editing car.gpkg/network and pedestrian.gpkg/network, export each edited layer back\n"
        "to GeoJSON (right-click layer -> Export -> Save Features As... -> GeoJSON, keep EPSG:25832 or WGS84,\n"
        "the import script re-projects either way) and run:\n\n"
        "    python tools/import_space_syntax_edited.py <edited_car.geojson> <edited_pedestrian.geojson>\n",
        encoding="utf-8")
    print(readme)


if __name__ == "__main__":
    main(*sys.argv[1:])
